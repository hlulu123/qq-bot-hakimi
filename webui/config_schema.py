class StoreError(Exception):
    """Base domain error with HTTP status code."""

    def __init__(self, message, status_code=400, extra=None):
        super().__init__(message)
        self.message = message
        self.status_code = status_code
        self.extra = extra or {}


class NotFoundError(StoreError):
    def __init__(self, message="资源不存在"):
        super().__init__(message, status_code=404)


class SensitiveMemoryError(StoreError):
    def __init__(self, matches, message=None):
        super().__init__(
            message or "公开记忆（public_profile）命中敏感词或隐私规则，禁止写入群聊可见档案",
            status_code=400,
            extra={"matches": matches},
        )
        self.matches = matches


